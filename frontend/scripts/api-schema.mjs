// src/api/schema.d.ts from the backend OpenAPI: ../docs/api/openapi-v1.json when it is there, else
// dumped in-process from ../backend with uv (no server, no keys).
// `--check` regenerates into a temp file and fails with a diff when the committed file is stale.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const committed = fileURLToPath(new URL('../../docs/api/openapi-v1.json', import.meta.url));
const backend = fileURLToPath(new URL('../../backend', import.meta.url));
const target = fileURLToPath(new URL('../src/api/schema.d.ts', import.meta.url));

function readOpenapi() {
  if (existsSync(committed)) return readFileSync(committed, 'utf8');
  if (!existsSync(join(backend, 'app/api'))) return null;
  const dump =
    'import json; from app.main import create_app; print(json.dumps(create_app().openapi()))';
  return execFileSync('uv', ['run', '--locked', '--quiet', 'python', '-c', dump], {
    cwd: backend,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
    maxBuffer: 64 * 1024 * 1024,
  });
}

const openapi = readOpenapi();
if (openapi === null) {
  console.log(`skip: neither ${committed} nor ${backend}/app/api exists, no API to type`);
  process.exit(0);
}
const header = '// Generated by `npm run api:gen` from the backend OpenAPI. Do not edit.\n\n';
const schema = header + astToString(await openapiTS(JSON.parse(openapi)));

if (!process.argv.includes('--check')) {
  writeFileSync(target, schema);
  console.log(`wrote ${target}`);
  process.exit(0);
}
const fresh = join(mkdtempSync(join(tmpdir(), 'api-schema-')), 'schema.d.ts');
writeFileSync(fresh, schema);
try {
  execFileSync('diff', ['-u', target, fresh], { stdio: 'inherit' });
  console.log('src/api/schema.d.ts is up to date');
} catch (error) {
  if (error.status !== 1) throw error; // diff exits 1 on a difference, 2 on trouble
  console.error('src/api/schema.d.ts is stale: run `npm run api:gen` and commit it');
  process.exit(1);
}
